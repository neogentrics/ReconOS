def row_bits(row):
    """Leftmost pixel is the high bit, which is how the drawing loop reads it."""
    v = 0
    for i, c in enumerate(row):
        if c == '#':
            v |= 0x80 >> i
    return v


def main():
    first, last = 0x20, 0x7E
    missing = [chr(c) for c in range(first, last + 1) if chr(c) not in ART]
    if missing:
        raise SystemExit(f"no art for: {''.join(missing)!r}")

    for name, art in ART.items():
        if len(art) != 8 or any(len(r) != 8 for r in art):
            raise SystemExit(f"glyph {name!r} is not eight rows of eight")

    print("/* ReconOS's console font: 8x8, ASCII 0x20 to 0x7E.")
    print(" *")
    print(" * Generated from the glyph art in scripts/make-font.py, which is the")
    print(" * source -- edit the pictures there, not the hex here. Committed rather")
    print(" * than generated at build time, because a header that only exists once")
    print(" * somebody has run a script is a header the build can be missing.")
    print(" *")
    print(" * Shared by the kernel's framebuffer console and the loader's menu, so")
    print(" * that a machine looks like one machine from the first pixel drawn to")
    print(" * the last. Leftmost pixel is the high bit of each byte.")
    print(" *")
    print(" * Drawn at double size: a 1280x800 screen is 80 columns by 50 rows.")
    print(" */")
    print("#ifndef RECON_FONT_H")
    print("#define RECON_FONT_H")
    print()
    print(f"#define RECON_FONT_FIRST 0x{first:02X}")
    print(f"#define RECON_FONT_LAST  0x{last:02X}")
    # Not RECON_FONT_W and RECON_FONT_H: the second collides with the include
    # guard, which the compiler caught as a redefinition. Spelt out instead.
    print("#define RECON_FONT_WIDTH  8")
    print("#define RECON_FONT_HEIGHT 8")
    print()
    print("static const unsigned char recon_font[%d][8] = {"
          % (last - first + 1))

    for code in range(first, last + 1):
        ch = chr(code)
        bits = ", ".join("0x%02X" % row_bits(r) for r in ART[ch])
        shown = "'\\\\'" if ch == '\\' else ("'" + ch + "'")
        print("\t{ %s },\t/* %s */" % (bits, shown))

    print("};")
    print()
    print("#endif /* RECON_FONT_H */")


main()
